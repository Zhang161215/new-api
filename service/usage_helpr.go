func ResponseText2Usage(c *gin.Context, responseText string, modeName string, promptTokens int) *dto.Usage {
	common.SetContextKey(c, constant.ContextKeyLocalCountTokens, true)
	usage := &dto.Usage{}
	usage.PromptTokens = promptTokens
	// 本站（计费宁愿多收不少收）：GPT 系有精确分词，取估算和精确计数的较大值。
	// tokenkit.Estimate 对英文 GPT 输出比 tiktoken 实数少约 10%，断流按估算结算会少收；
	// 其他模型 Count 内部就是 Estimate，结果不变。
	usage.CompletionTokens = max(tokenkit.Estimate(modeName, responseText), tokenkit.Count(modeName, responseText))
	usage.TotalTokens = usage.PromptTokens + usage.CompletionTokens
	return usage
}

func ValidUsage(usage *dto.Usage) bool {
	return usage != nil && (usage.PromptTokens != 0 || usage.CompletionTokens != 0)
}
